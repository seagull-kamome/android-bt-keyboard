package jp.kamome.btkeyboard

/** 複合 HID デバイス（キーボード / マウス / コンシューマコントロール）の定義 */
object HidDescriptor {
    const val ID_KEYBOARD = 1
    const val ID_MOUSE = 2
    const val ID_CONSUMER = 3

    @Suppress("RemoveRedundantCallsOfConversionMethods")
    val REPORT_MAP: ByteArray = intArrayOf(
        // --- Keyboard (Report ID 1): modifiers, reserved, key[6] ---
        0x05, 0x01, 0x09, 0x06, 0xA1, 0x01, 0x85, ID_KEYBOARD,
        0x05, 0x07, 0x19, 0xE0, 0x29, 0xE7, 0x15, 0x00, 0x25, 0x01,
        0x75, 0x01, 0x95, 0x08, 0x81, 0x02,       // modifier bits
        0x95, 0x01, 0x75, 0x08, 0x81, 0x01,       // reserved
        0x95, 0x06, 0x75, 0x08, 0x15, 0x00, 0x25, 0x65,
        0x05, 0x07, 0x19, 0x00, 0x29, 0x65, 0x81, 0x00, // key array
        0xC0,
        // --- Mouse (Report ID 2): buttons(3), x, y, wheel ---
        0x05, 0x01, 0x09, 0x02, 0xA1, 0x01, 0x85, ID_MOUSE,
        0x09, 0x01, 0xA1, 0x00,
        0x05, 0x09, 0x19, 0x01, 0x29, 0x03, 0x15, 0x00, 0x25, 0x01,
        0x75, 0x01, 0x95, 0x03, 0x81, 0x02,       // buttons
        0x75, 0x05, 0x95, 0x01, 0x81, 0x01,       // padding
        0x05, 0x01, 0x09, 0x30, 0x09, 0x31, 0x09, 0x38,
        0x15, 0x81, 0x25, 0x7F, 0x75, 0x08, 0x95, 0x03, 0x81, 0x06, // x, y, wheel (relative)
        0xC0, 0xC0,
        // --- Consumer Control (Report ID 3): 16-bit usage ---
        0x05, 0x0C, 0x09, 0x01, 0xA1, 0x01, 0x85, ID_CONSUMER,
        0x15, 0x00, 0x26, 0xFF, 0x03, 0x19, 0x00, 0x2A, 0xFF, 0x03,
        0x75, 0x10, 0x95, 0x01, 0x81, 0x00,
        0xC0,
    ).map { it.toByte() }.toByteArray()
}
